const header = "# generated by hostgen, do not edit\n"

var (
	ruleKey   = regexp.MustCompile(`^traefik\.http\.routers\.[^.]+\.rule$`)
	hostCall  = regexp.MustCompile(`\bHost\(([^)]*)\)`)
	quoted    = regexp.MustCompile("[`\"]([^`\"]+)[`\"]")
	validName = regexp.MustCompile(`^[a-z0-9_-]+(\.[a-z0-9_-]+)*$`)
)

// ---------------------------------------------------------------- config

type target struct{ path, ip string }

type pair struct{ parent, child string }

const (
	minBackoff = 5 * time.Second
	maxBackoff = 5 * time.Minute
)

// dockerID matches container and endpoint ids, which differ on every failed
// attempt and would otherwise make each retry error look new.
var dockerID = regexp.MustCompile(`[0-9a-f]{64}`)

type config struct {
	domain     string
	dockerSock string
	targets    []target
	exclude    map[string]bool
	restart    []string
	pairs      []pair
	exposedAll bool
	interval   time.Duration
	once       bool
}

func env(key, def string) string {
	if v := strings.TrimSpace(os.Getenv(key)); v != "" {
		return v
	}
	return def
}

func list(s string) []string {
	var out []string
	for _, p := range strings.Split(s, ",") {
		if p = strings.TrimSpace(p); p != "" {
			out = append(out, p)
		}
	}
	return out
}

func normalize(h string) (string, bool) {
	h = strings.TrimSuffix(strings.ToLower(strings.TrimSpace(h)), ".")
	return h, validName.MatchString(h)
}

func parseTargets(s string) ([]target, error) {
	var out []target
	for _, item := range list(s) {
		i := strings.LastIndex(item, "=")
		if i <= 0 {
			return nil, fmt.Errorf("TARGETS: want path=ip, got %q", item)
		}
		path, ip := strings.TrimSpace(item[:i]), strings.TrimSpace(item[i+1:])
		if net.ParseIP(ip) == nil {
			return nil, fmt.Errorf("TARGETS: invalid IP %q in %q", ip, item)
		}
		out = append(out, target{path: path, ip: ip})
	}
	if len(out) == 0 {
		return nil, errors.New("TARGETS is required")
	}
	return out, nil
}

func loadConfig() (config, error) {
	var c config
	var err error

	d, ok := normalize(env("DOMAIN", "jell0.online"))
	if !ok {
		return c, errors.New("DOMAIN: invalid domain")
	}
	c.domain = d
	c.dockerSock = env("DOCKER_SOCK", "/var/run/docker.sock")
	if c.targets, err = parseTargets(os.Getenv("TARGETS")); err != nil {
		return c, err
	}
	c.exclude = map[string]bool{}
	for _, p := range list(os.Getenv("EXCLUDE")) {
		h, ok := normalize(p)
		if !ok {
			return c, fmt.Errorf("EXCLUDE: invalid hostname %q", p)
		}
		c.exclude[h] = true
	}
	c.restart = list(os.Getenv("RESTART"))
	for _, item := range list(os.Getenv("NETNS_PAIRS")) {
		parent, child, ok := strings.Cut(item, ":")
		parent, child = strings.TrimSpace(parent), strings.TrimSpace(child)
		if !ok || parent == "" || child == "" || parent == child {
			return c, fmt.Errorf("NETNS_PAIRS: want parent:child, got %q", item)
		}
		c.pairs = append(c.pairs, pair{parent, child})
	}
	c.exposedAll = strings.EqualFold(env("EXPOSED_BY_DEFAULT", "false"), "true")
	if c.interval, err = time.ParseDuration(env("INTERVAL", "5s")); err != nil || c.interval < time.Second {
		return c, errors.New("INTERVAL: want a duration of at least 1s")
	}
	c.once = os.Getenv("ONCE") == "1"
	return c, nil
}

// ---------------------------------------------------------------- docker

type docker struct{ hc *http.Client }

func newDocker(sock string) *docker {
	tr := &http.Transport{
		DialContext: func(ctx context.Context, _, _ string) (net.Conn, error) {
			var d net.Dialer
			return d.DialContext(ctx, "unix", sock)
		},
		DisableKeepAlives: true,
	}
	return &docker{hc: &http.Client{Transport: tr}}
}

// labels returns the label set of every container Traefik would route:
// running ones, plus stopped ones labelled traefik.docker.allownonrunning=true
// (used by Sablier and similar scale-to-zero setups, where Traefik keeps the
// router while the container sleeps).
func (d *docker) labels(ctx context.Context) ([]map[string]string, error) {
	ctx, cancel := context.WithTimeout(ctx, 10*time.Second)
	defer cancel()
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, "http://docker/containers/json?all=1", nil)
	if err != nil {
		return nil, err
	}
	resp, err := d.hc.Do(req)
	if err != nil {
		return nil, fmt.Errorf("docker: %w", err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("docker: GET /containers/json: %s", resp.Status)
	}
	var cs []struct {
		Labels map[string]string
		State  string
	}
	if err := json.NewDecoder(resp.Body).Decode(&cs); err != nil {
		return nil, fmt.Errorf("docker: decode container list: %w", err)
	}
	out := make([]map[string]string, 0, len(cs))
	for _, c := range cs {
		if c.State == "running" || strings.EqualFold(strings.TrimSpace(c.Labels["traefik.docker.allownonrunning"]), "true") {
			out = append(out, c.Labels)
		}
	}
	return out, nil
}

type containerInfo struct {
	ID    string `json:"Id"`
	Name  string `json:"Name"`
	State struct {
		Status    string    `json:"Status"`
		StartedAt time.Time `json:"StartedAt"`
	} `json:"State"`
	HostConfig struct {
		NetworkMode string `json:"NetworkMode"`
	} `json:"HostConfig"`
}

// inspect returns a container's details, or nil when it does not exist.
func (d *docker) inspect(ctx context.Context, name string) (*containerInfo, error) {
	ctx, cancel := context.WithTimeout(ctx, 10*time.Second)
	defer cancel()
	u := "http://docker/containers/" + url.PathEscape(name) + "/json"
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, u, nil)
	if err != nil {
		return nil, err
	}
	resp, err := d.hc.Do(req)
	if err != nil {
		return nil, fmt.Errorf("docker: inspect %s: %w", name, err)
	}
	defer resp.Body.Close()
	if resp.StatusCode == http.StatusNotFound {
		return nil, nil
	}
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("docker: inspect %s: %s", name, resp.Status)
	}
	var ci containerInfo
	if err := json.NewDecoder(resp.Body).Decode(&ci); err != nil {
		return nil, fmt.Errorf("docker: decode inspect %s: %w", name, err)
	}
	return &ci, nil
}

// restart restarts a container by name. found is false when it does not exist.
func (d *docker) restart(ctx context.Context, name string) (found bool, err error) {
	ctx, cancel := context.WithTimeout(ctx, 60*time.Second)
	defer cancel()
	u := "http://docker/containers/" + url.PathEscape(name) + "/restart?t=3"
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, u, nil)
	if err != nil {
		return false, err
	}
	resp, err := d.hc.Do(req)
	if err != nil {
		return false, fmt.Errorf("docker: restart %s: %w", name, err)
	}
	defer resp.Body.Close()
	switch resp.StatusCode {
	case http.StatusNoContent:
		return true, nil
	case http.StatusNotFound:
		return false, nil
	}
	body, _ := io.ReadAll(io.LimitReader(resp.Body, 512))
	return false, fmt.Errorf("docker: restart %s: %s %s", name, resp.Status, strings.TrimSpace(string(body)))
}

// traefikHosts returns every name matched by a Host() rule in router labels.
// HostRegexp rules are ignored. Like Traefik, a container counts only when
// traefik.enable=true, or when exposedByDefault is set and the label is not
// traefik.enable=false.
func traefikHosts(sets []map[string]string, exposedByDefault bool) map[string]bool {
	out := map[string]bool{}
	for _, labels := range sets {
		enable := strings.ToLower(strings.TrimSpace(labels["traefik.enable"]))
		if enable == "false" || (!exposedByDefault && enable != "true") {
			continue
		}
		for k, v := range labels {
			if !ruleKey.MatchString(k) {
				continue
			}
			for _, call := range hostCall.FindAllStringSubmatch(v, -1) {
				for _, q := range quoted.FindAllStringSubmatch(call[1], -1) {
					if h, ok := normalize(q[1]); ok {
						out[h] = true
					}
				}
			}
		}
	}
	return out
}

// ---------------------------------------------------------------- output

// selectHosts keeps names under domain that are not excluded, sorted.
func selectHosts(raw map[string]bool, domain string, exclude map[string]bool) []string {
	out := make([]string, 0, len(raw))
	for h := range raw {
		if (h == domain || strings.HasSuffix(h, "."+domain)) && !exclude[h] {
			out = append(out, h)
		}
	}
	sort.Strings(out)
	return out
}

// render returns the conf file content for one dnsmasq instance.
func render(ip string, hosts []string) string {
	var b strings.Builder
	b.WriteString(header)
	for _, h := range hosts {
		fmt.Fprintf(&b, "host-record=%s,%s\nlocal=/%s/\n", h, ip, h)
	}
	return b.String()
}

// writeIfChanged replaces the file atomically, and only when the content
// differs. The temp file starts with a dot, which dnsmasq conf-dir skips.
func writeIfChanged(path, content string) (bool, error) {
	if old, err := os.ReadFile(path); err == nil && string(old) == content {
		return false, nil
	}
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return false, err
	}
	tmp := filepath.Join(dir, "."+filepath.Base(path)+".tmp")
	if err := os.WriteFile(tmp, []byte(content), 0o644); err != nil {
		return false, err
	}
	return true, os.Rename(tmp, path)
}

// ---------------------------------------------------------------- app

type retry struct {
	next    time.Time
	delay   time.Duration
	lastErr string
}

type app struct {
	cfg     config
	dk      *docker
	now     func() time.Time
	pending map[string]*retry
	warned  map[string]string
}

func newApp(cfg config) *app {
	return &app{
		cfg:     cfg,
		dk:      newDocker(cfg.dockerSock),
		now:     time.Now,
		pending: map[string]*retry{},
		warned:  map[string]string{},
	}
}

func (a *app) queue(name string, now time.Time) {
	if _, ok := a.pending[name]; !ok {
		a.pending[name] = &retry{next: now}
	}
}

func (a *app) tick(ctx context.Context) error {
	now := a.now()
	sets, err := a.dk.labels(ctx)
	if err != nil {
		return err
	}
	hosts := selectHosts(traefikHosts(sets, a.cfg.exposedAll), a.cfg.domain, a.cfg.exclude)
	for _, t := range a.cfg.targets {
		changed, err := writeIfChanged(t.path, render(t.ip, hosts))
		if err != nil {
			return err
		}
		if changed {
			log.Printf("wrote %s (%s): %d hosts: %s", t.path, t.ip, len(hosts), strings.Join(hosts, ", "))
			for _, n := range a.cfg.restart {
				a.queue(n, now)
			}
		}
	}
	a.checkPairs(ctx, now)
	a.runRestarts(ctx, now)
	return nil
}

// checkPairs queues a restart of each child whose parent started after it.
func (a *app) checkPairs(ctx context.Context, now time.Time) {
	for _, p := range a.cfg.pairs {
		pi, err := a.dk.inspect(ctx, p.parent)
		if err != nil || pi == nil {
			continue
		}
		ci, err := a.dk.inspect(ctx, p.child)
		if err != nil || ci == nil {
			continue
		}
		// A stopped child may be on purpose, and a crash looping parent is
		// left to its own restart policy until it stays up.
		if pi.State.Status != "running" || ci.State.Status != "running" {
			continue
		}
		if ref, ok := strings.CutPrefix(ci.HostConfig.NetworkMode, "container:"); ok &&
			ref != pi.ID && ref != p.parent && ref != strings.TrimPrefix(pi.Name, "/") {
			// Parent was recreated: child points at an id that is gone, and
			// only recreating child fixes that.
			if a.warned[p.child] != pi.ID {
				a.warned[p.child] = pi.ID
				log.Printf("%s is attached to an old %s container, a restart cannot fix it: run docker compose up -d %s",
					p.child, p.parent, p.child)
			}
			continue
		}
		if pi.State.StartedAt.After(ci.State.StartedAt) {
			if _, queued := a.pending[p.child]; !queued {
				log.Printf("%s started after %s, so %s lost its network, restarting it", p.parent, p.child, p.child)
				a.queue(p.child, now)
			}
		}
	}
}

// runRestarts attempts every due restart, backing off on failure.
func (a *app) runRestarts(ctx context.Context, now time.Time) {
	names := make([]string, 0, len(a.pending))
	for n := range a.pending {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		r := a.pending[n]
		if now.Before(r.next) {
			continue
		}
		found, err := a.dk.restart(ctx, n)
		if err != nil {
			r.delay = min(max(r.delay*2, minBackoff), maxBackoff)
			r.next = now.Add(r.delay)
			if msg := dockerID.ReplaceAllString(err.Error(), "<id>"); msg != r.lastErr {
				log.Printf("%s (retrying with backoff up to %s, logged once)", msg, maxBackoff)
				r.lastErr = msg
			}
			continue
		}
		delete(a.pending, n)
		switch {
		case !found:
			log.Printf("container %s not found, skipped (it reads the config when it starts)", n)
		case r.lastErr != "":
			log.Printf("restarted %s after earlier failures", n)
		default:
			log.Printf("restarted %s", n)
		}
	}
}

func (a *app) run(ctx context.Context) error {
	var lastErr string
	for {
		err := a.tick(ctx)
		switch {
		case err == nil:
			if lastErr != "" {
				log.Print("recovered")
				lastErr = ""
			}
		case err.Error() != lastErr:
			log.Print(err)
			lastErr = err.Error()
		}
		if a.cfg.once {
			if err == nil && len(a.pending) > 0 {
				err = fmt.Errorf("restart still pending for %d container(s)", len(a.pending))
			}
			return err
		}
		select {
		case <-ctx.Done():
			return nil
		case <-time.After(a.cfg.interval):
		}
	}
}

func main() {
	log.SetFlags(0)
	log.SetPrefix("hostgen: ")
	cfg, err := loadConfig()
	if err != nil {
		log.Fatal(err)
	}
	log.Printf("domain=%s interval=%s targets=%d restart=%v netnsPairs=%v exposedByDefault=%t",
		cfg.domain, cfg.interval, len(cfg.targets), cfg.restart, cfg.pairs, cfg.exposedAll)
	if len(cfg.restart) == 0 {
		log.Print("warning: RESTART is empty, dnsmasq will not see changes until it restarts")
	}
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	if err := newApp(cfg).run(ctx); err != nil {
		log.Fatal(err)
	}
}
